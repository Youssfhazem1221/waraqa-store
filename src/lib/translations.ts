import { ltr, RANGE_DASH } from './format';

export type Locale = 'en' | 'ar';

// Number ranges in the copy are joined with RANGE_DASH, like the computed ones
// (lib/format.ts): typed as a bare en dash, "3–7" broke after the dash.
const DAYS_EN = `3${RANGE_DASH}7`;
const DAYS_AR = `٣${RANGE_DASH}٧`;

// An amount in Arabic copy reads like the computed prices («٦٠ ج.م»,
// lib/format.ts), held to its currency by a no-break space. The legal pages
// keep the formal «جنيه».
const egp = (amount: string) => `${amount}\u00A0ج.م`;

// The mobile prefixes in the phone error, the bracketed list held on one line
// by no-break spaces (on phones it wrapped inside the brackets: «(010 أو 011
// أو» / «012 أو 015)»). In Arabic they stay in Latin digits, like the number
// typed above them, each isolated left to right.
const PHONE_PREFIXES = ['010', '011', '012', '015'];
const PHONE_PREFIXES_EN = PHONE_PREFIXES.join(',\u00A0');
const PHONE_PREFIXES_AR = PHONE_PREFIXES.map(ltr).join('\u00A0أو\u00A0');

